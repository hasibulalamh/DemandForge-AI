import { describe, expect, it } from "vitest";

import { buildPreviewDocument, PREVIEW_CSP } from "@/lib/demo/preview";
import { escapeHtml, renderDemo } from "@/lib/demo/render";
import type { DemoSpecOutput } from "@/lib/gemini/schemas";
import { demoSpecSchema } from "@/lib/gemini/schemas";
import { validateDemoFiles } from "@/lib/demo/validate";
import type { DemoFiles } from "@/lib/demo/types";

const spec: DemoSpecOutput = demoSpecSchema.parse({
  businessName: "Bright Path Dental",
  tagline: "Calm dentistry for busy families",
  industry: "dental care",
  heroHeadline: "Dentistry that fits your week",
  heroSubheadline: "Book, plan, and pay online with a team that explains every step.",
  ctaLabel: "Book a visit",
  palette: { primary: "#3f51b5", accent: "#ff7043", surface: "#f6f7fb", text: "#1d1b26" },
  fontStyle: "sans",
  services: [
    { name: "Routine care", description: "Check-ups and hygiene for the whole family." },
    { name: "Cosmetic dentistry", description: "Whitening and veneers with clear pricing." },
    { name: "Emergency visits", description: "Same-week appointments for urgent pain." },
  ],
  features: [
    { title: "Online booking", description: "Request a slot without phone tag." },
    { title: "Clear pricing", description: "Know the cost before you arrive." },
  ],
  faqs: [
    { question: "Do you accept new patients?", answer: "Yes, we welcome new families every week." },
    { question: "How long is a first visit?", answer: "Plan for about forty minutes." },
  ],
  footerNote: "Serving the greater Riverside area.",
  metaDescription: "Concept dental care website with online booking and transparent pricing.",
  serviceArea: "Riverside",
});

describe("renderDemo", () => {
  const { files, manifest } = renderDemo(spec, { templateName: "local-service" });

  it("produces exactly the allowed file set", () => {
    expect(Object.keys(files).sort()).toEqual([
      "README.md",
      "assets/css/styles.css",
      "assets/js/main.js",
      "index.html",
    ]);
  });

  it("passes its own safety validation", () => {
    const validation = validateDemoFiles(files);
    expect(validation.errors).toEqual([]);
    expect(validation.valid).toBe(true);
  });

  it("makes no external requests and includes the contract tags", () => {
    expect(files["index.html"]).toMatch(/<link rel="stylesheet" href="assets\/css\/styles\.css" \/>/);
    expect(files["index.html"]).toMatch(/<script src="assets\/js\/main\.js" defer><\/script>/);
    expect(files["index.html"]).not.toMatch(/https?:\/\//);
    expect(files["assets/css/styles.css"]).not.toMatch(/https?:\/\//);
    expect(files["index.html"]).toContain("Concept demo generated by DemandForge AI");
  });

  it("uses the fictional contact details and never the client's real ones", () => {
    expect(files["index.html"]).toContain("hello@example.com");
    expect(files["index.html"]).toContain("(555) 010-2030");
    expect(files["README.md"]).toMatch(/concept demo/i);
  });

  it("applies the palette from the specification", () => {
    expect(files["assets/css/styles.css"]).toContain("--color-primary: #3f51b5");
    expect(files["assets/css/styles.css"]).toContain("--color-accent: #ff7043");
  });

  it("records per-file checksums and a total size in the manifest", () => {
    expect(manifest.files).toHaveLength(4);
    expect(manifest.totalBytes).toBeGreaterThan(1_000);
    expect(manifest.checksum).toMatch(/^[0-9a-f]{64}$/);
    for (const file of manifest.files) {
      expect(file.checksum).toMatch(/^[0-9a-f]{64}$/);
      expect(file.bytes).toBeGreaterThan(0);
    }
  });
});

describe("escapeHtml", () => {
  it("neutralizes markup from model output", () => {
    expect(escapeHtml('<script>alert("x")</script>')).toBe(
      "&lt;script&gt;alert(&quot;x&quot;)&lt;/script&gt;",
    );
  });

  it("keeps model text from breaking out of the document", () => {
    const injected = renderDemo(
      demoSpecSchema.parse({ ...spec, businessName: "Bad </title><script>alert(1)</script>" }),
      { templateName: "portfolio" },
    );
    expect(injected.files["index.html"]).not.toContain("<script>alert(1)</script>");
    expect(validateDemoFiles(injected.files).valid).toBe(true);
  });
});

describe("validateDemoFiles", () => {
  const base: DemoFiles = renderDemo(spec, { templateName: "local-service" }).files;

  it("rejects unexpected files", () => {
    const result = validateDemoFiles({ ...base, "server.js": "console.log(1)" });
    expect(result.valid).toBe(false);
    expect(result.errors.join(" ")).toContain("Unexpected file");
  });

  it("rejects missing files and non-text values", () => {
    const rest: Record<string, unknown> = { ...base };
    delete rest["assets/js/main.js"];
    expect(validateDemoFiles(rest).valid).toBe(false);
    expect(validateDemoFiles({ ...base, "index.html": 42 }).valid).toBe(false);
  });

  it("rejects inline scripts and event handlers", () => {
    const inline = {
      ...base,
      "index.html": base["index.html"].replace("</head>", "<script>alert(1)</script></head>"),
    };
    expect(validateDemoFiles(inline).errors.join(" ")).toContain("exactly one script tag");

    const handler = {
      ...base,
      "index.html": base["index.html"].replace("<body", '<body onload="alert(1)"'),
    };
    expect(validateDemoFiles(handler).errors.join(" ")).toContain("Inline event handlers");
  });

  it("rejects frames, forms, and external URLs", () => {
    expect(
      validateDemoFiles({ ...base, "index.html": "<!doctype html><html><iframe src='x'></iframe>" }).valid,
    ).toBe(false);
    expect(
      validateDemoFiles({
        ...base,
        "index.html": base["index.html"].replace("<body", '<body><form action="https://evil.test"'),
      }).errors.join(" "),
    ).toContain("Frames, forms");
    expect(
      validateDemoFiles({
        ...base,
        "index.html": base["index.html"].replace("</head>", '<img src="https://evil.test/x.png"></head>'),
      }).errors.join(" "),
    ).toContain("External URLs");
  });

  it("rejects javascript: URLs and dangerous JavaScript APIs", () => {
    expect(validateDemoFiles({ ...base, "assets/js/main.js": "eval('2+2');" }).errors.join(" ")).toContain(
      "eval()",
    );
    expect(
      validateDemoFiles({ ...base, "assets/js/main.js": "fetch('https://evil.test');" }).errors.join(" "),
    ).toContain("network access");
    expect(
      validateDemoFiles({ ...base, "assets/js/main.js": "document.cookie = 'a=1';" }).errors.join(" "),
    ).toContain("document.cookie");
    expect(
      validateDemoFiles({ ...base, "assets/js/main.js": "window.open('https://evil.test');" }).errors.join(
        " ",
      ),
    ).toContain("window.open");
  });

  it("rejects syntax errors, unbalanced CSS, and CSS imports", () => {
    expect(validateDemoFiles({ ...base, "assets/js/main.js": "function (" }).errors.join(" ")).toContain(
      "syntax error",
    );
    expect(
      validateDemoFiles({ ...base, "assets/css/styles.css": "a { color: red;" }).errors.join(" "),
    ).toContain("unbalanced braces");
    expect(
      validateDemoFiles({
        ...base,
        "assets/css/styles.css": "@import url('https://evil.test/x.css');",
      }).errors.join(" "),
    ).toContain("@import");
  });

  it("rejects secret-like markers leaking into artifacts", () => {
    const result = validateDemoFiles({
      ...base,
      "assets/js/main.js": 'const k = "SUPABASE_SERVICE_ROLE_KEY";',
    });
    expect(result.valid).toBe(false);
    expect(result.errors.join(" ")).toContain("secret-like marker");
  });

  it("rejects oversized files", () => {
    const result = validateDemoFiles({
      ...base,
      "assets/js/main.js": `// ${"x".repeat(400 * 1024)}`,
    });
    expect(result.errors.join(" ")).toContain("per-file limit");
  });
});

describe("buildPreviewDocument", () => {
  const { files } = renderDemo(spec, { templateName: "saas-landing" });
  const preview = buildPreviewDocument(files);

  it("inlines the stylesheet and script so nothing is fetched", () => {
    expect(preview).not.toContain('href="assets/css/styles.css"');
    expect(preview).not.toContain('src="assets/js/main.js"');
    expect(preview).toContain("<style>");
    expect(preview).toContain("</script>");
    expect(preview).toContain("--color-primary: #3f51b5");
  });

  it("sandboxes the preview with an opaque origin", () => {
    expect(PREVIEW_CSP).toContain("sandbox allow-scripts");
    expect(PREVIEW_CSP).toContain("default-src 'none'");
    expect(PREVIEW_CSP).toContain("form-action 'none'");
  });

  it("escapes script terminators so a string cannot break out", () => {
    const malicious = { ...files, "assets/js/main.js": 'const x = "</script><img src=x>";' };
    const document = buildPreviewDocument(malicious);
    expect(document).toContain("<\\/script");
    expect(document).not.toContain("</script><img");
  });
});
